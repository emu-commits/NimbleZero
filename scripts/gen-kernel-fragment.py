#!/usr/bin/env python3
"""Generate board/cardputerzero/linux.fragment from the Raspberry Pi bcm2711_defconfig.

bcm2711_defconfig enables ~1300 modules for every HAT and USB gadget ever made.
The Cardputer Zero needs a small, known subset, so every '=m' symbol that is not
on the allowlist below is switched off.  tests/check-kernel-config.sh verifies
after the build that every REQUIRED symbol survived kconfig dependency resolution.

usage: gen-kernel-fragment.py <linux-src>/arch/arm64/configs/bcm2711_defconfig > linux.fragment
"""
import re,sys
KEEP = r"""
CFG80211 BRCMFMAC BRCMUTIL RFKILL RFKILL_INPUT
BT BT_RFCOMM BT_BNEP BT_HIDP BT_HCIUART BT_BCM BT_HCIBTUSB
I2C_BCM2835 I2C_CHARDEV I2C_MUX I2C_MUX_PINCTRL I2C_GPIO SPI_BCM2835 SPI_BCM2835AUX SPI_SPIDEV
DRM DRM_VC4 DRM_PANEL_MIPI_DBI DRM_DISPLAY_CONNECTOR DRM_SIMPLE_BRIDGE BACKLIGHT_PWM BACKLIGHT_GPIO
KEYBOARD_TCA8418 KEYBOARD_GPIO INPUT_UINPUT INPUT_EVDEV INPUT_JOYDEV INPUT_MOUSEDEV HID_.*
SND SND_.*TIMER SND_HRTIMER SND_SEQ.* SND_USB_AUDIO SND_SOC SND_BCM2835_SOC_I2S SND_SIMPLE_CARD SND_SOC_SIMPLE_AMPLIFIER SND_ALOOP SND_BCM2835
IIO IIO_.* BMI270_I2C BMC150_MAGN_I2C
RTC_DRV_DS1307
IR_.* RC_.* LIRC
MEDIA_SUPPORT VIDEO_DEV VIDEO_IMX219 VIDEO_BCM2835_UNICAM VIDEO_BCM2835_UNICAM_LEGACY VIDEO_ISP_BCM2835 VIDEO_BCM2835 VIDEO_CODEC_BCM2835 BCM2835_VCHIQ.* BCM_VC_SM.* USB_VIDEO_CLASS VIDEOBUF2.* V4L2.*
USB_CONFIGFS USB_ETH USB_G_SERIAL USB_GADGETFS USB_MASS_STORAGE USB_LIBCOMPOSITE USB_ROLE_SWITCH
USB_USBNET USB_NET_AX8817X USB_NET_AX88179_178A USB_NET_SR9700 USB_NET_SR9800 USB_NET_CDCETHER USB_NET_CDC_NCM USB_NET_CDC_EEM USB_NET_RNDIS_HOST USB_NET_CDC_SUBSET USB_RTL8152 USB_NET_SMSC95XX USB_LAN78XX MII
USB_STORAGE USB_UAS USB_ACM USB_SERIAL USB_SERIAL_GENERIC USB_SERIAL_FTDI_SIO USB_SERIAL_CP210X USB_SERIAL_CH341 USB_SERIAL_PL2303 USB_PRINTER
PWM_BCM2835 LEDS_TRIGGER_.* GPIO_SYSFS W1 W1_MASTER_GPIO
FUSE_FS OVERLAY_FS SQUASHFS EXFAT_FS NLS_.* ISO9660_FS UDF_FS F2FS_FS CONFIGFS_FS
IPV6 TUN WIREGUARD PPP PPP_.* PPPOE SLHC IP_NF_.*NONE
CRYPTO_.* CRC.* LIB.* ZRAM ZSMALLOC BLK_DEV_LOOP BLK_DEV_RAM BINFMT_MISC IKCONFIG
BCM2835_WDT BCM2835_THERMAL RASPBERRYPI_.* SENSORS_RASPBERRYPI_HWMON HW_RANDOM.* SERIAL_.* GPIO_.*FXL.*
UHID FB_TFT
""".split()
keep = re.compile('^(' + '|'.join(KEEP) + ')$')
out = ["# GENERATED by scripts/gen-kernel-fragment.py - do not edit by hand", ""]
n_off = n_keep = 0
for line in open(sys.argv[1]):
    m = re.match(r'CONFIG_(\w+)=m$', line.strip())
    if not m: continue
    if keep.match(m.group(1)): n_keep += 1
    else: out.append(f"# CONFIG_{m.group(1)} is not set"); n_off += 1
out += ["", "# --- Cardputer Zero additions ---"] + """
CONFIG_LOCALVERSION="-v8-cz"
# uncompressed modules: nothing to inflate on a slow CPU, and BusyBox/kmod need no codec
# CONFIG_MODULE_COMPRESS is not set
CONFIG_DRM_FBDEV_EMULATION=y
CONFIG_FRAMEBUFFER_CONSOLE=y
CONFIG_FONTS=y
CONFIG_FONT_6x8=y
CONFIG_FONT_8x16=y
CONFIG_PRINTK_TIME=y
CONFIG_IKCONFIG=y
CONFIG_IKCONFIG_PROC=y
CONFIG_DEVTMPFS=y
CONFIG_DEVTMPFS_MOUNT=y
CONFIG_ZRAM=m
# boot-critical bus drivers built in: the LCD path does not wait for module loading
CONFIG_I2C_BCM2835=y
CONFIG_SPI_BCM2835=y
CONFIG_INPUT_MATRIXKMAP=m
CONFIG_IIO_BUFFER=y
CONFIG_IIO_TRIGGERED_BUFFER=m
CONFIG_POWER_SUPPLY=y
# in-tree IMU drivers are enabled only to pull in the IIO helper code they select;
# post-build.sh removes them in favour of the M5Stack versions
CONFIG_BMI270_I2C=m
CONFIG_BMC150_MAGN_I2C=m
# drivers replaced by the M5Stack out-of-tree versions (nz-drivers package)
# CONFIG_BATTERY_BQ27XXX is not set
# never used on this board (FB_TFT core is kept: the M5Stack driver tree builds an fbtft variant too)
# CONFIG_DRM_V3D is not set
# CONFIG_KVM is not set
# CONFIG_VIRTUALIZATION is not set
# CONFIG_NFS_FS is not set
# CONFIG_NFSD is not set
# CONFIG_CIFS is not set
# CONFIG_BTRFS_FS is not set
# CONFIG_XFS_FS is not set
# CONFIG_MD is not set
# media: cameras only (without the filter every DVB frontend and tuner is built)
CONFIG_MEDIA_SUPPORT_FILTER=y
CONFIG_MEDIA_CAMERA_SUPPORT=y
CONFIG_MEDIA_PLATFORM_SUPPORT=y
CONFIG_MEDIA_SUBDRV_AUTOSELECT=y
# CONFIG_MEDIA_DIGITAL_TV_SUPPORT is not set
# CONFIG_MEDIA_ANALOG_TV_SUPPORT is not set
# CONFIG_MEDIA_RADIO_SUPPORT is not set
# CONFIG_MEDIA_SDR_SUPPORT is not set
# CONFIG_HAMRADIO is not set
# CONFIG_CAN is not set
# CONFIG_NET_SCHED is not set
# CONFIG_BPF_JIT is not set
# CONFIG_CGROUP_BPF is not set
# CONFIG_DEBUG_INFO is not set
# CONFIG_KGDB is not set
# CONFIG_FTRACE is not set
# CONFIG_SCSI_ISCSI_ATTRS is not set
# USB controller as a module: built in, its probe holds up the whole kernel for
# 0.73 s (initcall_debug on hardware); as a module udev loads it in the background.
# dwc_otg stays built in: config-safe.txt has no dwc2 overlay and uses it.
CONFIG_USB_DWC2=m
# Raspberry Pi 4/5 hardware: the CM0 (BCM2710A1) has no PCIe, xHCI, RP1, GENET or MACB
# CONFIG_ARCH_BRCMSTB is not set
# CONFIG_PCI is not set
# CONFIG_USB_XHCI_HCD is not set
# CONFIG_USB_DWC3 is not set
# CONFIG_MFD_RP1 is not set
# CONFIG_BCMGENET is not set
# CONFIG_MACB is not set
# CONFIG_PINCTRL_BCM2712 is not set
# no UEFI firmware, no initramfs (root= is the SD card). NUMA stays on: without it
# the VideoCore refuses the camera ISP's MMAL service ("Failed to open VCHI service
# connection", no /dev/video13), tested on hardware.
# CONFIG_EFI is not set
# CONFIG_BLK_DEV_INITRD is not set
# unused here (CGROUP_BPF is already off; nothing loads AppArmor profiles or reads audit)
# CONFIG_BPF_SYSCALL is not set
# CONFIG_MPTCP is not set
# CONFIG_SECURITY_APPARMOR is not set
# CONFIG_AUDIT is not set
# CONFIG_KPROBES is not set
# CONFIG_KALLSYMS_ALL is not set
# neither partition is F2FS: keep it for removable media, out of the kernel image
CONFIG_F2FS_FS=m
""".strip().split('\n')
print('\n'.join(out))
print(f"kept {n_keep} modules, disabled {n_off}", file=sys.stderr)
